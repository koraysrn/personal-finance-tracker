-- Initial schema for the personal account tracking application.
-- Uses portable SQL so the same migration runs on PostgreSQL (production)
-- and on H2 in PostgreSQL compatibility mode (tests).

CREATE TABLE app_user (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username           VARCHAR(64)  NOT NULL UNIQUE,
    password_hash      VARCHAR(100) NOT NULL,
    display_name       VARCHAR(128),
    locale             VARCHAR(16)  NOT NULL DEFAULT 'en_US',
    failed_login_count INT          NOT NULL DEFAULT 0,
    locked_until       TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE account (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(128)   NOT NULL,
    type            VARCHAR(32)    NOT NULL,
    currency        CHAR(3)        NOT NULL,
    opening_balance NUMERIC(18, 2) NOT NULL DEFAULT 0,
    credit_limit    NUMERIC(18, 2) NOT NULL DEFAULT 0,
    archived        BOOLEAN        NOT NULL DEFAULT FALSE,
    sort_order      INT            NOT NULL DEFAULT 0,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_account_credit_limit CHECK (credit_limit >= 0)
);

CREATE TABLE category (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(128) NOT NULL,
    type      VARCHAR(16)  NOT NULL,
    parent_id BIGINT REFERENCES category (id),
    icon      VARCHAR(64),
    color     VARCHAR(16),
    archived  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_category_name_type UNIQUE (name, type)
);

CREATE TABLE tag (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL UNIQUE
);

CREATE TABLE transaction_tx (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT        NOT NULL REFERENCES account (id),
    category_id     BIGINT REFERENCES category (id),
    type            VARCHAR(16)   NOT NULL,
    amount          NUMERIC(18, 2) NOT NULL,
    tx_date         DATE          NOT NULL,
    note            VARCHAR(1024),
    linked_tx_id    BIGINT REFERENCES transaction_tx (id),
    source          VARCHAR(16)   NOT NULL DEFAULT 'MANUAL',
    idempotency_key VARCHAR(64),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_tx_amount CHECK (amount > 0)
);

CREATE UNIQUE INDEX ux_tx_idempotency ON transaction_tx (idempotency_key);

CREATE TABLE transaction_tags (
    transaction_id BIGINT NOT NULL REFERENCES transaction_tx (id) ON DELETE CASCADE,
    tag_id         BIGINT NOT NULL REFERENCES tag (id) ON DELETE CASCADE,
    PRIMARY KEY (transaction_id, tag_id)
);

CREATE TABLE budget (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  BIGINT        NOT NULL REFERENCES category (id),
    budget_year  INT           NOT NULL,
    budget_month INT           NOT NULL,
    amount       NUMERIC(18, 2) NOT NULL,
    CONSTRAINT uq_budget_category_month UNIQUE (category_id, budget_year, budget_month),
    CONSTRAINT chk_budget_month CHECK (budget_month BETWEEN 1 AND 12),
    CONSTRAINT chk_budget_amount CHECK (amount > 0)
);

CREATE TABLE recurring_transaction (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT        NOT NULL REFERENCES account (id),
    category_id BIGINT        NOT NULL REFERENCES category (id),
    type        VARCHAR(16)   NOT NULL,
    amount      NUMERIC(18, 2) NOT NULL,
    frequency   VARCHAR(16)   NOT NULL,
    day_of_month INT,
    day_of_week  INT,
    note        VARCHAR(1024),
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    start_date  DATE          NOT NULL,
    end_date    DATE,
    next_run    DATE          NOT NULL,
    last_run    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT chk_rec_amount CHECK (amount > 0),
    CONSTRAINT chk_rec_day_of_month CHECK (day_of_month IS NULL OR day_of_month BETWEEN 1 AND 31)
);

CREATE TABLE shedlock (
    name       VARCHAR(64) NOT NULL PRIMARY KEY,
    lock_until TIMESTAMP WITH TIME ZONE NOT NULL,
    locked_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    locked_by  VARCHAR(255) NOT NULL
);

CREATE TABLE settings (
    setting_key   VARCHAR(64)  NOT NULL PRIMARY KEY,
    setting_value VARCHAR(255) NOT NULL
);
